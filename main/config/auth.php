<?php

use Illuminate\Foundation\Auth\User;

return [

    /*
    |--------------------------------------------------------------------------
    | Authentication Defaults
    |--------------------------------------------------------------------------
    |
    | Пользовательской аутентификации у сервиса нет (s2s Bearer-токены,
    | см. блок api ниже) — guards оставлены в минимальной комплектации,
    | которую ожидает фреймворк.
    |
    */

    'defaults' => [
        'guard' => 'web',
        'passwords' => 'users',
    ],

    'guards' => [
        'web' => [
            'driver' => 'session',
            'provider' => 'users',
        ],
    ],

    'providers' => [
        'users' => [
            'driver' => 'eloquent',
            'model' => User::class,
        ],
    ],

    /*
    |--------------------------------------------------------------------------
    | API-токены (service-to-service)
    |--------------------------------------------------------------------------
    |
    | Потребители API — внутренние сервисы
    | компании (монолит, billing, ...), их единицы. По одному токену на
    | сервис-потребитель, чтобы отзыв не задевал остальных. Конечные
    | пользователи в этот API напрямую не ходят — от их имени действует
    | доверенный внутренний сервис (поэтому user_id приходит в запросе).
    |
    | При росте числа потребителей или самообслуживании — переход на
    | выдачу ключей через хранилище / OAuth2 client credentials.
    |
    */

    'api' => [
        /*
         * Пары «токен:секрет_подписи» через запятую. Токен идентифицирует
         * сервис, секретом подписываются запросы (HMAC) — сам секрет
         * по сети не передаётся.
         */
        'clients' => env('API_AUTH_CLIENTS', ''),

        /*
         * Окно валидности X-Timestamp в секундах (защита от replay).
         */
        'signature_ttl' => (int) env('API_SIGNATURE_TTL', 300),

        /*
         * Алгоритм HMAC-подписи (любой из hash_hmac_algos()).
         */
        'signature_algo' => env('API_SIGNATURE_ALGO', 'sha256'),
    ],

];
